"""Round 097 maverick: for EVERY LNA at n (all key groups), the Z-congruence invariants of S = C + C^T that SNF probes miss:
signature, det, and the multiset {(order x, x^T S x mod 2) : x in A = S^-1 Z^n / Z^n} of the discriminant quadratic form (a complete invariant of the
genus of an even lattice of this signature, Nikulin 1.9.4; the multiset is only a separator, so equal multisets are re-checked by disc_iso in cartanZ).
Counts key groups split by the invariant, and reports the quipu-named members' spread.
usage (repo root): timeout 10m .venv/bin/python workshop/rounds/097/maverick_genusscan.py N"""
import sys, collections
import numpy as np
from flint import fmpz_mat
from quivermutation import coxeterTables as ct
N = int(sys.argv[1]); keys = ct.lnaKeys(N); groups = collections.defaultdict(list)
for rl, k in keys.items(): groups[k].append(rl)

def inv(rl):
    C = np.array(ct.lnaCartanMatrix(N, rl)).astype(int); S = C + C.T
    M = fmpz_mat(S.tolist()); d = int(M.det())
    if d == 0: return ("sing",)
    adj = np.array([[int(x) for x in row] for row in (M.inv() * d if False else (M.adjugate().tolist()))], dtype=object) if hasattr(M, "adjugate") else None
    if adj is None:
        from fractions import Fraction
        Q = M.inv(); adj = np.array([[int(Q[i, j] * d) for j in range(N)] for i in range(N)], dtype=object)
    ad = abs(d); ev = np.linalg.eigvalsh(S.astype(float)); sg = (int((ev > 1e-9).sum()), int((ev < -1e-9).sum()))
    if ad > 4000: return (d, sg, "big")
    # elements v in Z^N mod S Z^N  <->  x = S^-1 v ; encode x by (adj v) mod |d| ; generated by e_j
    cols = [tuple(int(adj[i, j]) % ad for i in range(N)) for j in range(N)]
    zero = tuple([0] * N); el = {zero}
    for c in cols:
        if c in el: continue
        new = set(el); cur = c
        while cur not in el:
            new |= {tuple((a + b) % ad for a, b in zip(e, cur)) for e in el}; cur = tuple((a + b) % ad for a, b in zip(cur, c))
        el = new
    # x = y/ad (y integer vector = adj v mod ad); x^T S x = y^T S y / ad^2 ; mod 2 -> exact integer arithmetic mod 2 ad^2
    Sl = S.astype(object); hist = collections.Counter()
    for y in el:
        yv = np.array(y, dtype=object); num = int(yv @ Sl @ yv) % (2 * ad * ad)
        # order of y in (Z/ad)^N
        from math import gcd
        g = ad
        for t in y: g = gcd(g, t)
        order = ad // g
        hist[(order, collections.Fraction(num, ad * ad) if False else (num, ad * ad))] += 1
    from fractions import Fraction
    h = tuple(sorted((o, Fraction(n_, dd)) for (o, (n_, dd)), c in hist.items() for _ in range(c)))
    return (d, sg, h)

split = 0; tot = 0; rows = []
for k, v in groups.items():
    vals = collections.Counter(); 
    for rl in v: vals[inv(rl)] += 1
    tot += 1
    if len(vals) > 1:
        split += 1; rows.append((len(v), len(vals), sorted(vals.values(), reverse=True)[:6]))
print("N", N, "key groups", tot, "groups split by (det, sig, q_S multiset)", split)
for r in sorted(rows, reverse=True)[:25]: print("  size", r[0], "classes", r[1], "class sizes", r[2])
