def repo_input(A):
    import networkx as nx
    key = Counter(); ek = {}
    q = nx.MultiDiGraph(); q.add_nodes_from(range(1, A.n + 1))
    for k, (a, b, _) in enumerate(A.arrows):
        ek[k] = (a + 1, b + 1, key[(a, b)]); q.add_edge(*ek[k]); key[(a, b)] += 1
    rels = [{tuple(ek[k] for k in p): c for p, c in r.items()} for r in A.rels]
    return q, rels

def repo_children(A, i):
    from quivermutation import procedure, arrowPaths as ap
    from tests.helpers import quiet
    q, rels = repo_input(A); res = {}
    for name, f in (('F', procedure.mutateAtVertex), ('R', procedure.mutateLeftAtVertex)):
        try:
            nq, nr = quiet(f, q, rels, i + 1); nq, nr = quiet(procedure.reduce, nq, nr)
        except Exception as e:
            res[name] = ('err', type(e).__name__); continue
        cyc = ap.hasOrientedCycle(nq); n = A.n
        G = [[0] * n for _ in range(n)]
        for t, h, k in nq.edges(keys=True): G[t - 1][h - 1] += 1
        N = None
        if not cyc:
            C = ap.cartanMatrix(nq, nr, exact=True); N = [[C[b][a] for b in range(n)] for a in range(n)]
        res[name] = (N, G, cyc)
    try: gF = procedure.isMutable(q, rels, i + 1)
    except Exception as e: gF = 'err:' + type(e).__name__
    try: gR = procedure.isMutable(*procedure._opposite(q, rels), i + 1)
    except Exception as e: gR = 'err:' + type(e).__name__
    return res, gF, gR

def verdict(child, inv):
    N, G, cyc = child; _, M, Ar = inv
    gm = (G == sc.T(Ar)); nm = None if N is None else (N == sc.T(M))
    return gm and (nm is not False), nm

