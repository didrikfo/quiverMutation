class AlgG:
    def __init__(s, n, arrows, rels, quotient):
        s.n = n; s.arrows = [(a, b, k) for k, (a, b) in enumerate(arrows)]   # index = arrow id
        s.rels = rels            # list of dict {path(tuple of arrow ids): coef}
        s.quotient = quotient; s._all = {}; s._red = {}; s._pa = {}
        s.zero = [next(iter(r)) for r in rels if len(r) == 1]
    def allpaths(s, u, w, cap=40):
        if (u, w) in s._all: return s._all[(u, w)]
        out = []
        def rec(v, p):
            if v == w: out.append(tuple(p))
            if len(p) >= cap: raise RuntimeError('path cap (infinite dimension?)')
            for k, (a, b, _) in enumerate(s.arrows):
                if a == v: rec(b, p + [k])
        rec(u, []); s._all[(u, w)] = out; return out
    def end(s, p, u): return s.arrows[p[-1]][1] if p else u
    def _setup(s, u, w):
        if (u, w) in s._red: return
        pa = s.allpaths(u, w); ix = {p: i for i, p in enumerate(pa)}; rows = []
        for r in s.rels:
            r0 = next(iter(r)); x = s.arrows[r0[0]][0]; y = s.arrows[r0[-1]][1]
            for a in s.allpaths(u, x):
                for b in s.allpaths(y, w):
                    v = [0] * len(pa)
                    for q, c in r.items(): v[ix[a + q + b]] = (v[ix[a + q + b]] + c) % P
                    if any(v): rows.append(v)
        R, piv = sc.rref(rows, len(pa)) if rows else ([], [])
        free = [c for c in range(len(pa)) if c not in piv]
        s._pa[(u, w)] = [pa[c] for c in free]
        red = {}
        for r, c in zip(R, piv): red[pa[c]] = {pa[f]: (-r[f]) % P for f in free if r[f] % P}
        s._red[(u, w)] = (red, set(free) and {pa[f] for f in free})
    def paths(s, u, w):
        if not s.quotient: return s._mono_paths(u, w)
        s._setup(u, w); return s._pa[(u, w)]
    def _nz(s, p):
        return not any(p[i:i + len(z)] == z for z in s.zero for i in range(len(p) - len(z) + 1))
    def _mono_paths(s, u, w):
        if (u, w) in s._pa: return s._pa[(u, w)]
        out = []
        def rec(v, p):
            if v == w: out.append(tuple(p))
            if len(p) > 40: raise RuntimeError('infinite')
            for k, (a, b, _) in enumerate(s.arrows):
                if a == v and s._nz(tuple(p) + (k,)): rec(b, p + [k])
        rec(u, []); s._pa[(u, w)] = out; return out
    def compose(s, p_after, p_before):
        q = p_after + p_before
        if not s.quotient: return {q: 1} if s._nz(q) else {}
        u = s.arrows[q[0]][0] if q else None
        if not q: return {(): 1}
        w = s.arrows[q[-1]][1]; s._setup(u, w)
        red = s._red[(u, w)][0]
        return dict(red[q]) if q in red else {q: 1}

def is_minimal(A):
    """no relation lies in the ideal generated by the others (quotient mode only)"""
    for j, r in enumerate(A.rels):
        B = AlgG(A.n, [(a, b) for a, b, _ in A.arrows], A.rels[:j] + A.rels[j + 1:], True)
        tot = Counter()
        for q, c in r.items():
            u = A.arrows[q[0]][0]; w = A.arrows[q[-1]][1]; B._setup(u, w)
            red = B._red[(u, w)][0]
            for t, d in (red[q].items() if q in red else [(q, 1)]): tot[t] = (tot[t] + c * d) % P
        if any(tot.values()): continue
        return False
    return True

# ---- vector-valued Dmat and comp_classes (override sc's) ----
def Dmat(A, U, V, m):
    S = sc.homspace(A, U, V, m); T = sc.homspace(A, U, V, m + 1)
    ti = {b: i for i, b in enumerate(T)}; cols = []
    for (n, a, b, p) in S:
        col = {}
        for (b1, b2), comb in V.d.get(n + m, {}).items():
            if b1 != b: continue
            for q, c in comb.items():
                for r, cr in A.compose(q, p).items():
                    key = ti[(n, a, b2, r)]; col[key] = (col.get(key, 0) + c * cr) % P
        for (a0, a1), comb in U.d.get(n - 1, {}).items():
            if a1 != a: continue
            for q, c in comb.items():
                for r, cr in A.compose(p, q).items():
                    key = ti[(n - 1, a0, b, r)]; col[key] = (col.get(key, 0) - (1 if m % 2 == 0 else -1) * c * cr) % P
        cols.append(col)
    return [[cols[j].get(i, 0) for j in range(len(S))] for i in range(len(T))], S, T

def comp_classes(A, hUV, hVW, hUW):
    tab = {}; idx = {b: i for i, b in enumerate(hUW.S)}
    for i, f in enumerate(hUV.basis):
        for j, g in enumerate(hVW.basis):
            out = [0] * len(hUW.S)
            for ff, cf in zip(hUV.S, f):
                if not cf: continue
                for gg, cg in zip(hVW.S, g):
                    if not cg: continue
                    (n, a, b, p), (n2, b2, c, q) = ff, gg
                    if n2 != n or b2 != b: continue
                    for r, cr in A.compose(q, p).items():
                        k = idx[(n, a, c, r)]; out[k] = (out[k] + cf * cg * cr) % P
            tab[(i, j)] = hUW.coords(out)
    return tab
sc.Dmat = Dmat; sc.comp_classes = comp_classes

