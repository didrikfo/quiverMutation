def gen(kind, n, rng):
    if kind in 'PN':
        arrows = [(a, b) for a in range(n) for b in range(a + 1, n) if rng.random() < 0.38]
        if kind == 'P': arrows += [x for x in list(arrows) if rng.random() < 0.35]; arrows.sort()
    else:
        arrows = [(a, b) for a in range(n) for b in range(n) if a != b and rng.random() < 0.3]
    if len(arrows) < n - 1 or set(v for a, b in arrows for v in (a, b)) != set(range(n)): return None
    A0 = AlgG(n, arrows, [], False)
    def sparsepaths(L):
        out = []
        def rec(p):
            if len(p) == L: out.append(tuple(p)); return
            v = A0.arrows[p[-1]][1]
            for k, (a, b, _) in enumerate(A0.arrows):
                if a == v: rec(p + [k])
        for k in range(len(arrows)): rec([k])
        return out
    rels = []
    for p in sparsepaths(2):
        if rng.random() < (0.35 if kind != 'C' else 0.5): rels.append({p: 1})
    if kind != 'C':
        for p in sparsepaths(3):
            if rng.random() < 0.2: rels.append({p: 1})
    if kind == 'N':
        byend = {}
        for L in (2, 3):
            for p in sparsepaths(L): byend.setdefault((A0.arrows[p[0]][0], A0.arrows[p[-1]][1], L), []).append(p)
        for ps in byend.values():
            if len(ps) >= 2 and rng.random() < 0.7:
                p, q = rng.sample(ps, 2); rels.append({p: 1, q: P - 1})
        if not any(len(r) > 1 for r in rels): return None
    if kind == 'C':
        if not any(True for _ in rels): return None
        try:
            B = AlgG(n, arrows, rels, False)
            for u in range(n):
                for w in range(n): B.paths(u, w)
        except RuntimeError: return None
        return B
    return AlgG(n, arrows, rels, True)

def sweep(kind, n, seeds):
    cnt = Counter(); exs = []
    s0 = int(os.environ.get('SEED0', '0'))
    for seed in range(s0, s0 + seeds):
        A = gen(kind, n, random.Random(seed))
        if A is None: continue
        cnt['parents'] += 1
        tag = ''
        if kind == 'N':
            mn = is_minimal(A); ml = max(len(next(iter(r))) for r in A.rels if len(r) > 1)
            tag = ' [relations minimal %s, longest commutativity rel arrow length %d]' % (mn, ml); cnt['parents' + tag] += 1
        for i in range(n):
            hasout = any(a == i for a, _, _ in A.arrows); hasin = any(b == i for _, b, _ in A.arrows)
            if any(a == b == i for a, b, _ in A.arrows): continue
            try:
                invR = sc.invariants(A, i, 'R'); invL = sc.invariants(A, i, 'L')
                kids, gF, gR = repo_children(A, i)
            except Exception as e:
                cnt['crash ' + type(e).__name__ + ' ' + str(e)[:40]] += 1; exs.append(('crash', seed, i)); continue
            differ = (invR[1], invR[2]) != (invL[1], invL[2])
            for name, inv, other, gate, has in (('F', invR, invL, gF, hasout), ('R', invL, invR, gR, hasin)):
                if not has: continue
                til = inv[0]
                cnt['%s: gate %s, tilting %s%s' % (name, gate, til, tag)] += 1
                if gate != til: exs.append(('gate!=tilt', name, seed, i, gate, til, tag))
                kid = kids[name]
                if kid[0] == 'err': cnt['%s repo refusal %s (tilting %s)' % (name, kid[1], til)] += 1; continue
                if not til: continue
                ok, nm = verdict(kid, inv); cnt['%s tilting step: own side matches %s (Cartan checked %s, child cyclic %s)%s' % (name, ok, nm is not None, kid[2], tag)] += 1
                if not ok: exs.append(('nomatch', name, seed, i, tag))
                if differ:
                    o, _ = verdict(kid, other); cnt['%s power (T_R,T_L differ): other side matches %s' % (name, o)] += 1
    for k in sorted(cnt): print(cnt[k], k)
    print('exceptions:', exs[:12], 'total', len(exs))
    if os.environ.get('ALLEXC'):
        for e in exs: print('EXC', e)

