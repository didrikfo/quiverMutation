"""Round 103 (theorist), answer to referee item 1: machine check of the loop lemma on random parents.
Independent of the library.  Parent A = kQ/I, Q a random multigraph (parallel arrows and loops-free, cyclic or acyclic), I generated by
monomial relations, commutativity relations and random linear combinations (all of length >= 2) plus rad^L (admissible, finite-dim), over F_p.
Facts used (Oppermann Constr. 2.2): the minimal model of A has, between a and b, as many arrows of degree m >= 1 as dim Ext^{m+1}(S_a,S_b)
(degree 1 = minimal relations).  We compute dim Ext^k(S_a,S_b) k <= KMAX+1 from minimal projective resolutions of the simples (module
representations, kernels, projective covers; no library code) and check:
  (L1) every degree-m arrow a->b (m = 1..KMAX) has an oriented path a -> b of length >= 1 in Q0;   (L2) hence every degree >= 1 LOOP at a has a on a Q0 cycle.
Sanity: Ext^1 count = #arrows, Ext^2 count (degree 1) = minimal relations number (checked against dim I/(I rad+rad I) computed separately).
usage: .venv/bin/python -W ignore workshop/rounds/103/theorist_loopmodel.py [seed] [N] [KMAX]"""
import sys, random, itertools
import numpy as np
P = 32003
def rref(M):
    M = M.copy() % P; r = 0; piv = []
    for c in range(M.shape[1]):
        if r >= M.shape[0]: break
        nz = np.nonzero(M[r:, c])[0]
        if len(nz) == 0: continue
        k = r + nz[0]; M[[r, k]] = M[[k, r]]
        M[r] = (M[r] * pow(int(M[r, c]), P - 2, P)) % P
        for i in range(M.shape[0]):
            if i != r and M[i, c]: M[i] = (M[i] - M[i, c] * M[r]) % P
        piv.append(c); r += 1
    return M[:r], piv
def nullspace(M):  # columns spanning {x: Mx=0}
    n = M.shape[1]
    if M.shape[0] == 0: return np.eye(n, dtype=np.int64)
    R, piv = rref(M); free = [c for c in range(n) if c not in piv]
    N = np.zeros((n, len(free)), dtype=np.int64)
    for j, f in enumerate(free):
        N[f, j] = 1
        for i, pc in enumerate(piv): N[pc, j] = (-R[i, f]) % P
    return N
def solve(B, Y):  # X with B X = Y (B full column rank)
    k = B.shape[1]
    R, piv = rref(np.hstack([B, Y]))
    X = np.zeros((k, Y.shape[1]), dtype=np.int64)
    for i, pc in enumerate(piv):
        assert pc < k, 'not in span'
        X[pc] = R[i, k:]
    return X

class Alg:
    def __init__(s, n, arrows, rels, L):
        s.n, s.arr, s.L = n, arrows, L
        s.out = {v: [i for i, (a, b) in enumerate(arrows) if a == v] for v in range(n)}
        # paths: (start, tuple of arrow ids), length < L, grouped by (start,end)
        s.paths = {}; s.end = {}
        for a in range(n):
            lvl = [(a, ())]
            for l in range(L):
                for p in lvl:
                    e = a if not p[1] else arrows[p[1][-1]][1]
                    s.paths.setdefault((a, e), []).append(p); s.end[p] = e
                nxt = []
                for p in lvl:
                    e = s.end[p]
                    nxt += [(a, p[1] + (i,)) for i in s.out[e]]
                lvl = nxt
        s.idx = {k: {p: j for j, p in enumerate(v)} for k, v in s.paths.items()}
        s.rels = rels
        s.build()
    def build(s):
        s.nf = {}; s.basis = {}
        for a in range(s.n):
            for v in range(s.n):
                key = (a, v); pl = s.paths.get(key, [])
                rows = []
                for (x, y, vec) in s.rels:  # vec: dict path(tuple of arrows) -> coeff, path from x to y
                    for u in s.paths.get((a, x), []):
                        for w in s.paths.get((y, v), []):
                            row = np.zeros(len(pl), dtype=np.int64); ok = False
                            for q, c in vec.items():
                                full = (a, u[1] + q + w[1])
                                if len(full[1]) < s.L: row[s.idx[key][full]] = (row[s.idx[key][full]] + c) % P; ok = True
                            if ok: rows.append(row)
                if rows: R, piv = rref(np.array(rows))
                else: R, piv = np.zeros((0, len(pl)), dtype=np.int64), []
                s.nf[key] = (R, piv)
                s.basis[key] = [j for j in range(len(pl)) if j not in piv]
    def reduce(s, key, vec):  # vec over paths(key) -> coords in basis
        R, piv = s.nf[key]; vec = vec.copy() % P
        for i, pc in enumerate(piv):
            if vec[pc]: vec = (vec - vec[pc] * R[i]) % P
        return vec[s.basis[key]]

def build_proj(A, a):
    d = [len(A.basis[(a, v)]) for v in range(A.n)]
    mats = []
    for ai, (u, w) in enumerate(A.arr):
        Mx = np.zeros((d[w], d[u]), dtype=np.int64)
        for c, j in enumerate(A.basis[(a, u)]):
            p = A.paths[(a, u)][j]; q = (a, p[1] + (ai,))
            if len(q[1]) >= A.L: continue  # zero (rad^L = 0)
            key = (a, w); vec = np.zeros(len(A.paths[key]), dtype=np.int64); vec[A.idx[key][q]] = 1
            Mx[:, c] = A.reduce(key, vec)
        mats.append(Mx)
    return d, mats
def apply_path(mats, arr, p, vec):
    for ai in p[1]: vec = (mats[ai] @ vec) % P
    return vec
def cover(A, mod):  # minimal projective cover of module (d, mats): returns multiplicities and kernel module
    d, mats = mod; n = A.n; gens = []
    for v in range(n):
        if d[v] == 0: continue
        cols = [mats[i] for i, (u, w) in enumerate(A.arr) if w == v and d[u] > 0]
        im = np.hstack(cols).T % P if cols else np.zeros((0, d[v]), dtype=np.int64)
        R, piv = rref(im) if im.shape[0] else (im, [])
        for c in range(d[v]):
            if c not in piv:
                e = np.zeros(d[v], dtype=np.int64); e[c] = 1; gens.append((v, e))
    mult = [sum(1 for g in gens if g[0] == v) for v in range(n)]
    # projective sum: at vertex w, blocks per generator
    pr = {}; pd = [0] * n; offs = []
    for gi, (v, e) in enumerate(gens):
        dd, mm = build_proj(A, v); pr[gi] = (dd, mm)
        offs.append([pd[w] for w in range(n)])
        for w in range(n): pd[w] += dd[w]
    phi = [np.zeros((d[w], pd[w]), dtype=np.int64) for w in range(n)]
    for gi, (v, e) in enumerate(gens):
        for w in range(n):
            for c, j in enumerate(A.basis[(v, w)]):
                p = A.paths[(v, w)][j]
                phi[w][:, offs[gi][w] + c] = apply_path(mats, A.arr, p, e)
    Pm = []
    for ai, (u, w) in enumerate(A.arr):
        Mx = np.zeros((pd[w], pd[u]), dtype=np.int64)
        for gi in range(len(gens)):
            dd, mm = pr[gi]
            Mx[offs[gi][w]:offs[gi][w] + dd[w], offs[gi][u]:offs[gi][u] + dd[u]] = mm[ai]
        Pm.append(Mx)
    K = [nullspace(phi[w]) if d[w] else np.eye(pd[w], dtype=np.int64) for w in range(n)]
    kd = [K[w].shape[1] for w in range(n)]
    km = []
    for ai, (u, w) in enumerate(A.arr):
        if kd[u] == 0 or kd[w] == 0: km.append(np.zeros((kd[w], kd[u]), dtype=np.int64)); continue
        km.append(solve(K[w], (Pm[ai] @ K[u]) % P))
    return mult, (kd, km)

def ext_dims(A, KMAX):
    """E[k][a][b] = dim Ext^k(S_a,S_b), k = 0..KMAX+1"""
    n = A.n; E = []
    for a in range(n):
        d = [1 if v == a else 0 for v in range(n)]
        mod = (d, [np.zeros((d[w], d[u]), dtype=np.int64) for (u, w) in A.arr]); rows = []
        for k in range(KMAX + 2):
            mult, mod = cover(A, mod); rows.append(mult)
            if sum(mod[0]) == 0: rows += [[0] * n] * (KMAX + 1 - k); break
            if sum(mod[0]) > 600: return None
        E.append(rows)
    return [[[E[a][k][b] for b in range(n)] for a in range(n)] for k in range(KMAX + 2)]

def reach(n, arr):
    R = [[False] * n for _ in range(n)]
    for a, b in arr: R[a][b] = True
    for k in range(n):
        for i in range(n):
            for j in range(n):
                if R[i][k] and R[k][j]: R[i][j] = True
    return R

def random_parent(rng, cyc):
    while True:
        n = rng.choice([3, 4, 5])
        if cyc:
            arr = [(rng.randrange(n), rng.randrange(n)) for _ in range(rng.randint(n, n + 3))]
            arr = [(a, b) for a, b in arr if a != b]
        else:
            arr = []
            for _ in range(rng.randint(n, n + 3)):
                a, b = sorted(rng.sample(range(n), 2)); arr.append((a, b))
        if not arr: continue
        L = rng.choice([4, 5]) if cyc else n
        R = reach(n, arr); iscyc = any(R[i][i] for i in range(n))
        if iscyc != cyc: continue
        A0 = Alg(n, arr, [], L)
        # candidate relations: pairs/triples of paths of length 2..L-1 with same endpoints
        cands = {}
        for key, pl in A0.paths.items():
            for p in pl:
                if 2 <= len(p[1]) < L: cands.setdefault(key, []).append(p[1])
        rels = []
        keys = list(cands)
        for _ in range(rng.randint(1, 4)):
            if not keys: break
            key = rng.choice(keys); ps = cands[key]
            kind = rng.choice(['mono', 'comm', 'lin'])
            if kind == 'mono' or len(ps) < 2: vec = {rng.choice(ps): 1}
            elif kind == 'comm': q1, q2 = rng.sample(ps, 2); vec = {q1: 1, q2: P - 1}
            else: qs = rng.sample(ps, min(len(ps), 3)); vec = {q: rng.randrange(1, P) for q in qs}
            rels.append((key[0], key[1], vec))
        return n, arr, rels, L, iscyc

def sanity():
    # E-211 parent, vertices 0..3 = 1..4: a:0->1, s:1->2, b:2->3, c:3->2; relations a s, s b c, c b.  Ext^2 total must be 3 (3 minimal relations).
    arr = [(0, 1), (1, 2), (2, 3), (3, 2)]
    rels = [(0, 2, {(0, 1): 1}), (1, 2, {(1, 2, 3): 1}), (3, 3, {(3, 2): 1})]
    A = Alg(4, arr, rels, 8); E = ext_dims(A, 2)
    assert sum(map(sum, E[2])) == 3 and E[2][3][3] == 1, E[2]       # c b is a degree-1 loop at vertex 4
    # parallel arrows x,y: 0->1 and z:1->2 with commutativity-free monomial x z = 0 only: Ext^2 = 1
    A = Alg(3, [(0, 1), (0, 1), (1, 2)], [(0, 2, {(0, 2): 1})], 4); E = ext_dims(A, 2)
    assert sum(map(sum, E[2])) == 1 and sum(map(sum, E[1])) == 3
    # Koszul dual numbers k[x]/x^2 on a loop is excluded (non-admissible?) -- here loop x with x^2 = 0 : Ext^k = 1 for all k
    A = Alg(1, [(0, 0)], [(0, 0, {(0, 0): 1})], 4); E = ext_dims(A, 3)
    assert [E[k][0][0] for k in range(5)] == [1, 1, 1, 1, 1], E
    print('sanity ok')
if __name__ == '__main__':
    sanity()
    seed = int(sys.argv[1]) if len(sys.argv) > 1 else 1; N = int(sys.argv[2]) if len(sys.argv) > 2 else 120
    KMAX = int(sys.argv[3]) if len(sys.argv) > 3 else 3
    rng = random.Random(seed)
    tot = dict(cyc=0, acyc=0, skipped=0, loops_cyc=0, parents_with_loop=0, viol_reach=0, viol_loop=0, arrows_ok=0, gens=0, par=0, nonmono=0)
    byk = {k: 0 for k in range(1, KMAX + 1)}
    for t in range(N):
        cyc = (t % 2 == 0)
        n, arr, rels, L, iscyc = random_parent(rng, cyc)
        A = Alg(n, arr, rels, L); E = ext_dims(A, KMAX)
        if E is None: tot['skipped'] += 1; continue
        tot['cyc' if iscyc else 'acyc'] += 1
        tot['par'] += len(set(arr)) < len(arr); tot['nonmono'] += any(len(v) > 1 for _, _, v in rels)
        assert sum(map(sum, E[1])) == len(arr), 'Ext^1 != arrows'
        R = reach(n, arr); haveloop = False
        for m in range(1, KMAX + 1):
            for a in range(n):
                for b in range(n):
                    c = E[m + 1][a][b]
                    if c:
                        tot['gens'] += c; byk[m] += c
                        if not R[a][b]: tot['viol_reach'] += 1
                        if a == b:
                            tot['loops_cyc'] += c; haveloop = True
                            if not R[a][a]: tot['viol_loop'] += 1
        tot['parents_with_loop'] += haveloop
        if not iscyc: assert not haveloop
    print('seed', seed, 'N', N, 'KMAX', KMAX, tot, 'generators by degree', byk)
