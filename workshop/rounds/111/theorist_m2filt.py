"""Round 111 theorist, T5/H-023, model M2 (free degree-1 loop f at i, d f = 0; E-284).
Letters of kM: bbar=m(.,b,.) d=c v; c=m(a,b,.) d=0; fbar=m(.,f,.) d=u v; u=m(a,f,.) d=0; v=a* d=0; theta1=f a^-1: d=theta2 v - v fbar; theta2=a f a^-1: d=v u.
Proof route: filter by g = number of letters in {bbar, fbar, theta1}.  d lowers or keeps g; d0 (g-preserving part) has d0 bbar = d0 fbar = 0,
d0 theta1 = -v fbar, d0 theta2 = v u: Lemma A shape (E-240).  This script computes H(I) (I = ideal of the Thetas and their differentials, E-284's test)
for (a) the true d, (b) d0, (c) control: star-letter ideal under d0 (must give H != 0), and checks d0^2 = 0 and that I is d0-closed.
Usage (repo root): timeout 10m .venv/bin/python -W ignore workshop/rounds/111/theorist_m2filt.py [WMAX]"""
import importlib.util, sys
sp = importlib.util.spec_from_file_location('lf', 'workshop/rounds/106/theorist_loopfilt.py')
lf = importlib.util.module_from_spec(sp); sp.loader.exec_module(lf)
W = int(sys.argv[1]) if len(sys.argv) > 1 else 10
G = {('m', None, 'b', None): 1, ('m', None, 'f', None): 1, ('m', None, 'f', 'a'): 1}
g = lambda L: G.get(L, 0)
orig = lf.opp.M.partial_letter
def p0(s, L):
    return {w: c for w, c in orig(s, L).items() if sum(g(x) for x in w) == g(L)}
def pfilt(s, L):   # check g never rises (filtration is preserved)
    for w in orig(s, L): assert sum(g(x) for x in w) <= g(L), (L, w)
    return orig(s, L)
lf.opp.M.partial_letter = pfilt
q = lf.MODELS['M2_loop1_dphi=0']()
print('(a) true d, filtration check passed if no assertion; M2:'); lf.run('M2_d', q, W)
lf.opp.M.partial_letter = p0
print('(b) d0 (g-preserving part)'); lf.run('M2_d0', lf.MODELS['M2_loop1_dphi=0'](), W)
print('(c) control under d0: closed ideal generated by the star letters (must give H != 0)'); lf.run('M2_d0_stars', lf.MODELS['M2_loop1_dphi=0'](), W, stars=True)
