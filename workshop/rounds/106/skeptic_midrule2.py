# (3) independent redundancy check: minimal relations = dim I - dim(JI+IJ), I generated by engine rels
def paths_of(m):
    adj = collections.defaultdict(list)
    for e in m.arrows(): adj[e[0]].append(e[1])
    P = []
    def rec(p):
        P.append(tuple(p))
        for w in adj[p[-1]]: rec(p + [w])
    for u in {e[0] for e in m.arrows()} | {e[1] for e in m.arrows()}: rec([u])
    return P
def minrels(m):
    P = paths_of(m); idx = collections.defaultdict(dict)
    for p in P: idx[(p[0], p[-1])].setdefault(p, len(idx[(p[0], p[-1])]))
    gens = []
    for rel in m.rels:
        assert len(rel) <= 2, rel
        gens.append([(tuple(t), (1 if j == 0 else -1)) for j, t in enumerate(rel)])
    def span(filt):
        rows = collections.defaultdict(list)
        for g in gens:
            s, t = g[0][0][0], g[0][0][-1]
            for p in P:
                if p[-1] != s: continue
                for q in P:
                    if q[0] != t: continue
                    if not filt(len(p) - 1 + len(q) - 1): continue
                    vec = collections.Counter()
                    for tp, c in g: vec[p[:-1] + tp + q[1:]] += c
                    rows[(p[0], q[-1])].append(vec)
        tot = 0
        for key, vs in rows.items():
            ix = idx[key]; M = np.zeros((len(vs), len(ix)))
            for a, vec in enumerate(vs):
                for pth, c in vec.items(): M[a, ix[pth]] += c
            tot += np.linalg.matrix_rank(M)
        return tot
    return span(lambda n: True) - span(lambda n: n >= 1)
