"""Round 106 (theorist), answers to referee: near-miss controls, models with two loops / degree-3 loop at i, other sign set.
Usage (repo root): .venv/bin/python -W ignore workshop/rounds/106/theorist_loopfilt2.py WMAX part   (part: ctrl | models | sign)"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import theorist_loopfilt as lf
orig = lf.opp.M
SIGN = [-1]
lf.opp.M = lambda q, sg: orig(q, {'last': SIGN[0]})
M = lf.MODELS
# M7: two degree-1 loops at i: d f = (a,b), d h = 0
M['M7_two_loops'] = lambda: lf.mk({'a': (0,1,0), 'b': (1,0,0), 'f': (0,0,1), 'h': (0,0,1)}, ['a'], {'f': {('a','b'): 1}}, {'a': 1, 'b': 2, 'f': 3, 'h': 3})
# M7b: two degree-1 loops, d f = (a,b), d h = -(a,b)
M['M7b_two_loops_both'] = lambda: lf.mk({'a': (0,1,0), 'b': (1,0,0), 'f': (0,0,1), 'h': (0,0,1)}, ['a'], {'f': {('a','b'): 1}, 'h': {('a','b'): -1}}, {'a': 1, 'b': 2, 'f': 3, 'h': 3})
# M8: degree-3 loop k on top of M3b; d k fixed by d^2 = 0 (hand computation): variant A d k = (g,a,b) - (f,f,a,b); variant B d k = (g,a,b) + (a,b,g) - (f,a,b,f) (coefficients found by search so that d^2 = 0 on kQ)
def m8(dk):
    return lambda: lf.mk({'a': (0,1,0), 'b': (1,0,0), 'f': (0,0,1), 'g': (0,0,2), 'k': (0,0,3)}, ['a'],
        {'f': {('a','b'): 1}, 'g': {('f','a','b'): 1, ('a','b','f'): -1}, 'k': dk}, {'a': 1, 'b': 2, 'f': 3, 'g': 6, 'k': 9})
M['M8_loop3_A'] = m8({('g','a','b'): 1, ('f','f','a','b'): -1})
M['M8_loop3_B'] = m8({('g','a','b'): 1, ('a','b','g'): 1, ('f','a','b','f'): -1})
if __name__ == '__main__':
    W = int(sys.argv[1]); part = sys.argv[2]
    m1 = 'M1_loop1_dphi=ba'
    if part == 'ctrl':
        q = M[m1](); mm, letters, wt = lf.setup(q)
        th = [L for L in letters if L[0]=='m' and L[3] is not None]; print('theta letters M1:', th)
        stars = [L for L in letters if L[0]=='s']
        print('N1 near-miss: ideal generated by ONE theta only', th[0]); lf.run('M1_one_theta0', q, W, pick=lambda ls: [th[0]])
        print('N1b near-miss: ONE theta only', th[1]); lf.run('M1_one_theta1', M[m1](), W, pick=lambda ls: [th[1]])
        print('N2 near-miss: I plus the star letter a*'); lf.run('M1_I_plus_star', M[m1](), W, pick=lambda ls: th + stars)
        print('N2b I plus the phi letter itself'); lf.run('M1_I_plus_phi', M[m1](), W, pick=lambda ls: th + [('m', None, 'f', None)])
        print('N3 model M3b (4 thetas), drop one'); q3 = M['M3b_loop2_dfnonzero'](); mm, ls, wt = lf.setup(q3)
        t3 = [L for L in ls if L[0]=='m' and L[3] is not None]; lf.run('M3b_drop_one', q3, W, pick=lambda ls: t3[1:])
    elif part == 'models':
        for n in ['M7_two_loops', 'M7b_two_loops_both', 'M8_loop3_A', 'M8_loop3_B']: lf.run(n, M[n](), W)
    elif part == 'sign':
        for sg in (+1, -1):
            SIGN[0] = sg; print('=== last sign', sg)
            for n in [m1, 'M3_loop2_junction', 'M3b_loop2_dfnonzero', 'M4_two_alpha', 'M5_loop_two_paths']: lf.run(n, M[n](), W)
