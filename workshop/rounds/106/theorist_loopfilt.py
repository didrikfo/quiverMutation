P = 1000003

def mk(arrows, A, d, w):
    q = opp.Q(arrows, A, 0); q.d = d; q.w = w; return q

# arrows: name -> (src, tgt, deg); words applied-first.  vertex 0 = i.
MODELS = {}
# M1: Construction-2.2 model of kQ/(a then b), Q: a: i->j, b: j->i.  phi loop deg 1, d phi = (a,b).  Ext^2(S_i,S_i) = 1.
MODELS['M1_loop1_dphi=ba'] = lambda: mk({'a': (0, 1, 0), 'b': (1, 0, 0), 'f': (0, 0, 1)}, ['a'], {'f': {('a', 'b'): 1}}, {'a': 1, 'b': 2, 'f': 3})
