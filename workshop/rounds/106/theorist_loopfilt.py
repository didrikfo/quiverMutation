MODELS['M3b_loop2_dfnonzero'] = lambda: mk({'a': (0, 1, 0), 'b': (1, 0, 0), 'f': (0, 0, 1), 'g': (0, 0, 2)}, ['a'],
    {'f': {('a', 'b'): 1}, 'g': {('f', 'a', 'b'): 1, ('a', 'b', 'f'): -1}}, {'a': 1, 'b': 2, 'f': 3, 'g': 6})
# M4: two A-arrows a1: i->j, a2: i->j, loop f with d f = (a1,b) - (a2,b)
MODELS['M4_two_alpha'] = lambda: mk({'a1': (0, 1, 0), 'a2': (0, 1, 0), 'b': (1, 0, 0), 'f': (0, 0, 1)}, ['a1', 'a2'],
    {'f': {('a1', 'b'): 1, ('a2', 'b'): -1}}, {'a1': 1, 'a2': 1, 'b': 2, 'f': 3})
# M5: loop f plus a second A-arrow m: i->k and e: k->j; d f = (a,b) + (m,e,b)  (path i->k->j->i)
MODELS['M5_loop_two_paths'] = lambda: mk({'a': (0, 1, 0), 'b': (1, 0, 0), 'f': (0, 0, 1), 'm': (0, 2, 0), 'e': (2, 1, 0)}, ['a', 'm'],
    {'f': {('a', 'b'): 1, ('m', 'e', 'b'): 1}}, {'a': 2, 'b': 2, 'f': 4, 'm': 1, 'e': 1})
# M6: no loop at all, same quiver (a, b, m, e) with a degree-1 arrow u: j->i  (control: the case E-235 proves), d u = (e',..) none: d u = 0
MODELS['M6_noloop_control'] = lambda: mk({'a': (0, 1, 0), 'b': (1, 0, 0), 'u': (1, 0, 1), 'm': (0, 2, 0), 'e': (2, 1, 0)}, ['a'],
    {'u': {('e', 'b'): 0}} and {}, {'a': 1, 'b': 2, 'u': 2, 'm': 2, 'e': 1})
def setup(q, ctrl=None):
    m = opp.M(q, {'last': -1})
    star = [('s', al) for al in sorted(q.A)]
    letters = opp.all_letters(q) + star
    def wt(L):
        if L[0] == 's': return -q.w[L[1]]
        _, a, p, b = L
        return q.w[p] + (q.w[a] if a else 0) - (q.w[b] if b else 0)
    for L in letters:
        if L[0] == 'm': assert wt(L) >= 1, (L, wt(L))
    return m, letters, wt

def words(m, letters, wt, s, t, W):
    out = []
    wA = max(-wt(L) for L in letters if L[0] == 's')
    def rec(cur, v, w):
        if w == W and v == t and cur: out.append(tuple(cur))
        if len(cur) >= 3 * (W + wA) + 2: return
        for L in letters:
            if m.src(L) == v and w + wt(L) <= W + wA:
                cur.append(L); rec(cur, m.tgt(L), w + wt(L)); cur.pop()
    rec([], s, 0); return out

def reduce_into(piv, row):
    row = {c: int(round(v)) % P for c, v in row.items() if int(round(v)) % P}
    while row:
        c = min(row, key=repr)
        if c in piv:
            f = row[c]
            for cc, vv in piv[c].items():
                nv = (row.get(cc, 0) - f * vv) % P
                if nv: row[cc] = nv
                else: row.pop(cc, None)
        else:
            inv = pow(row[c], P - 2, P)
            row = {cc: vv * inv % P for cc, vv in row.items()}
            piv[c] = row; return row
    return None

def mul(E, F):   # concatenation (applied-first): E then F
    out = {}
    for u, c in E.items():
        for v, e in F.items(): opp.add(out, u + v, c * e)
    return out

def run(name, q, W, flip=False, verbose=True, stars=False, pick=None):
    m, letters, wt = setup(q)
    theta = [L for L in letters if L[0] == 'm' and L[3] is not None]
    dth = {L: m.partial({(L,): 1}) for L in theta}
    if pick: theta = pick(letters); dth = {L: m.partial({(L,): 1}) for L in theta}   # control: ideal generated by chosen letters and their differentials
    if stars: theta = [L for L in letters if L[0] == 's']; dth = {L: {} for L in theta}   # control: closed ideal generated by the star letters
    if flip:   # planted error: reverse the sign of the phi.a* term of every d(theta)
        for L in theta:
            dth[L] = {w: (-c if any(x[0] == 's' for x in w) and len(w) == 2 else c) for w, c in dth[L].items()}
    dim = lambda L: m.deg(L)
    wdeg = m.wdeg
    # checks: d^2 = 0 on all letters
    d2 = sum(1 for L in letters if m.partial(m.partial({(L,): 1})))
    # weight homogeneity of d
    nonhom = 0
    for L in letters:
        for w in m.partial({(L,): 1}):
            if sum(wt(x) for x in w) != wt(L): nonhom += 1
    bad_cells = 0; cells = 0; tot_I = 0; notclosed = 0; hsum = 0; details = []
    for Wt in range(1, W + 1):
        for s in range(3):
            for t in range(3):
                ws = words(m, letters, wt, s, t, Wt)
                if not ws: continue
                bydeg = {}
                for w in ws: bydeg.setdefault(wdeg(w), []).append(w)
                Ibasis = {}; piv_d = {}
                for d, L in bydeg.items():
                    piv = {}
                    for w in L:
                        if any(x in dth for x in w): reduce_into(piv, {w: 1})
                    piv_d[d] = piv
                # also generators u d(theta) v whose theta-containing word is in a different degree handled above (same degree: d theta has deg-1) -> need degree of u theta v = d+1
                for d in list(bydeg):
                    pass
                # second pass: u (d theta) v lies in degree d where u theta v has degree d+1
                for d1, L in bydeg.items():
                    for w in L:
                        for k, x in enumerate(w):
                            if x in dth:
                                piv = piv_d.setdefault(d1 - 1, {})
                                reduce_into(piv, {w[:k] + u + w[k+1:]: c for u, c in dth[x].items()})
                rk = {}; dimI = {}
                for d, piv in piv_d.items():
                    dimI[d] = len(piv)
                    img = {}
                    r = 0
                    for row in piv.values():
                        e = m.partial(row)
                        # closure check
                        e = {w: c % P for w, c in e.items() if c % P}
                        if e:
                            if reduce_into(piv_d.setdefault(d - 1, {}) if False else dict(piv_d.get(d - 1, {})), dict(e)) is not None: notclosed += 1
                            if reduce_into(img, e) is not None: r += 1
                    rk[d] = r
                for d in dimI:
                    h = dimI[d] - rk.get(d, 0) - rk.get(d + 1, 0)
                    cells += 1; tot_I += dimI[d]
                    if h: bad_cells += 1; hsum += h; details.append((Wt, s, t, d, dimI[d], h))
    r = dict(model=name, d2_bad=d2, nonhomog=nonhom, thetas=len(theta), cells=cells, dimI=tot_I, notclosed=notclosed, bad_cells=bad_cells, sumH=hsum)
    if verbose:
        print(r)
        for x in details[:6]: print('   H(I)!=0 at (weight, src, tgt, deg, dimI, h) =', x)
    return r

