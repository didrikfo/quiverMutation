MODELS['M2_loop1_dphi=0'] = lambda: mk({'a': (0, 1, 0), 'b': (1, 0, 0), 'f': (0, 0, 1)}, ['a'], {}, {'a': 1, 'b': 2, 'f': 3})
# M3: degree-1 loop f (d f = 0) and degree-2 loop g with d g = f.(a b) + (a b).f  (both orders; the second has a Delta-junction at i), |dg| = 1
