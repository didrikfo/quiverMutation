"""Relations as linear combinations of paths, with exact ideal arithmetic.

The rest of this repo models a relation as a *set* of paths: `[[1,2,5],[1,3,5]]`
means the two paths are identified, `[[1,2,3]]` means that path is zero.  There
are no coefficients, so the model cannot tell `p - q = 0` from `p + q = 0`, and
cannot represent `2p + r = 0` at all.  That is the limitation this module lifts.

Why integers and not just signs.  Signs alone are not closed under the
arithmetic: from `p + q + r = 0` and `p - q = 0` follows `2p + r = 0`, which has
no expression with coefficients in {-1, 0, +1}.  Any implementation that stops
at signs has to either refuse that combination or silently drop the 2.  Integer
coefficients are the smallest choice that closes, and cost nothing over signs --
the representation is the same dict, with a wider value type.  Rational
coefficients would also work and change nothing here; the row reduction below is
over the rationals already.

The central operation is deciding whether a combination of paths lies in the
ideal generated by the relations.  For a fixed source and target the paths
between them span a finite-dimensional vector space, the ideal meets it in a
subspace spanned by `v r u` for relations `r` and paths `u`, `v`, and membership
is then a linear algebra question with an exact answer.  That is what the
set-of-paths model can only approximate: it recognises a path as zero when a
zero relation appears as a contiguous piece of it, and propagates equalities
through commutativity relations by a partial closure that misses chains.
"""

from fractions import Fraction

import networkx as nx


def combination(terms):
    """A linear combination of paths, as a dict path -> nonzero coefficient.

    `terms` is an iterable of (path, coefficient) pairs, or of paths, which are
    taken with coefficient 1.  Paths are normalised to tuples and repeated paths
    are summed; terms that cancel are dropped.
    """
    result = {}
    for term in terms:
        if isinstance(term, tuple) and len(term) == 2 and not isinstance(term[1], (list, tuple)):
            path, coefficient = term
        else:
            path, coefficient = term, 1
        path = tuple(path)
        result[path] = result.get(path, 0) + coefficient
    return {path: c for path, c in result.items() if c != 0}


def fromPathSet(paths):
    """Read a relation in the set-of-paths model as a sum with every sign +1.

    This is the reading the mutation procedure's step 4 produces directly
    (sum over the arrows out of i of alpha* alpha beta = 0).  It is *a* reading
    of a relation written without coefficients, not the only one: a two-path
    relation used as a commutativity relation means the difference, not the sum.
    The two agree on everything this module computes about dimensions, and
    differ on which individual paths are zero.
    """
    return combination(tuple(path) for path in paths)


def toPathSet(comb):
    """Back to the set-of-paths model, dropping the coefficients."""
    return sorted(list(path) for path in comb)


def add(*combs):
    terms = []
    for comb in combs:
        terms.extend(comb.items())
    return combination(terms)


def scale(comb, factor):
    return combination((path, coefficient * factor) for path, coefficient in comb.items())


def negate(comb):
    return scale(comb, -1)


def source(comb):
    """The common source vertex of every path, or None for the zero combination."""
    return next(iter(comb))[0] if comb else None


def target(comb):
    return next(iter(comb))[-1] if comb else None


def isHomogeneous(comb):
    """Whether every path in the combination has the same source and target."""
    if not comb:
        return True
    paths = list(comb)
    return all(p[0] == paths[0][0] and p[-1] == paths[0][-1] for p in paths)


def leftDivide(comb, arrowTarget):
    """r / alpha, for the arrow alpha out of source(r) that lands on arrowTarget.

    The paper's notation: the combination of the paths of r that begin with
    alpha, with alpha removed.  Zero if no path of r begins with alpha.
    """
    return combination(
        (path[1:], coefficient)
        for path, coefficient in comb.items()
        if len(path) > 1 and path[1] == arrowTarget
    )


def rightDivide(comb, arrowSource):
    """The mirror of leftDivide: drop the last arrow, which starts at arrowSource."""
    return combination(
        (path[:-1], coefficient)
        for path, coefficient in comb.items()
        if len(path) > 1 and path[-2] == arrowSource
    )


def preCompose(comb, path):
    """path then comb: every path of comb with `path` glued on the front."""
    prefix = tuple(path)[:-1]
    return combination((prefix + p, c) for p, c in comb.items())


def postCompose(comb, path):
    suffix = tuple(path)[1:]
    return combination((p + suffix, c) for p, c in comb.items())


def allPathsBetween(quiver, sourceVertex, targetVertex):
    """Every path from source to target, as tuples, shortest first.

    Only simple paths, which is exactly right for an acyclic quiver and is what
    the rest of the repo assumes throughout.
    """
    if sourceVertex == targetVertex:
        return [(sourceVertex,)]
    paths = [tuple(p) for p in nx.all_simple_paths(quiver, sourceVertex, targetVertex)]
    return sorted(paths, key=lambda p: (len(p), p))


def idealSpanningSet(quiver, relations, sourceVertex, targetVertex):
    """The combinations `v r u` spanning the ideal's part between two vertices.

    For each relation r from a to b, every path u from source to a and every
    path v from b to target gives an element of the ideal lying in the span of
    the paths from source to target.  Together they span the whole of the
    ideal's intersection with that span.
    """
    spanning = []
    for relation in relations:
        if not relation:
            continue
        relationSource, relationTarget = source(relation), target(relation)
        for before in allPathsBetween(quiver, sourceVertex, relationSource):
            extendedLeft = preCompose(relation, before)
            for after in allPathsBetween(quiver, relationTarget, targetVertex):
                spanning.append(postCompose(extendedLeft, after))
    return [element for element in spanning if element]


def _rowReduce(rows):
    """Reduced row echelon form over the rationals, as a list of pivot rows.

    Rows are dicts basis element -> coefficient.  Returns (pivots, rows) where
    pivots maps a basis element to the row it heads.
    """
    pivots = {}
    for row in rows:
        row = {k: Fraction(v) for k, v in row.items() if v != 0}
        while row:
            head = min(row)
            if head not in pivots:
                pivots[head] = {k: v / row[head] for k, v in row.items()}
                break
            factor = row[head]
            pivotRow = pivots[head]
            row = {
                k: row.get(k, Fraction(0)) - factor * pivotRow.get(k, Fraction(0))
                for k in set(row) | set(pivotRow)
            }
            row = {k: v for k, v in row.items() if v != 0}
    return pivots


def idealBasis(quiver, relations, sourceVertex, targetVertex):
    """A row-reduced basis of the ideal's part between two vertices."""
    spanning = idealSpanningSet(quiver, relations, sourceVertex, targetVertex)
    return _rowReduce([dict(element) for element in spanning])


def isInIdeal(quiver, relations, comb):
    """Whether a combination of paths is zero in the algebra.

    Exact: it reduces the combination against a row-reduced basis of the ideal
    between its source and target, rather than looking for a zero relation
    inside it.
    """
    if not comb:
        return True
    if not isHomogeneous(comb):
        raise ValueError("a combination must have one source and one target: {0}".format(comb))
    pivots = idealBasis(quiver, relations, source(comb), target(comb))
    row = {k: Fraction(v) for k, v in comb.items()}
    while row:
        head = min(row)
        if head not in pivots:
            return False
        factor = row[head]
        pivotRow = pivots[head]
        row = {
            k: row.get(k, Fraction(0)) - factor * pivotRow.get(k, Fraction(0))
            for k in set(row) | set(pivotRow)
        }
        row = {k: v for k, v in row.items() if v != 0}
    return True


def homDimension(quiver, relations, sourceVertex, targetVertex):
    """dim of the span of the paths source -> target in the algebra.

    The number of paths between the two vertices, minus the rank of the ideal
    between them.  For source == target the trivial path contributes 1 and is
    never in an admissible ideal, so the result is at least 1 there.

    This is the exact version of numberOfPathsUpToRels, and the entry the Cartan
    matrix wants.
    """
    paths = allPathsBetween(quiver, sourceVertex, targetVertex)
    if not paths:
        return 0
    rank = len(idealBasis(quiver, relations, sourceVertex, targetVertex))
    return len(paths) - rank


def cartanMatrixExact(pathAlg, relationReading=fromPathSet):
    """The Cartan matrix, computed by linear algebra over the ideal.

    Entry (j, i) is dim e_j (kQ/I) e_i, the dimension of the span of the paths
    from vertex i to vertex j.  `relationReading` turns a relation in the
    repo's set-of-paths form into a linear combination; the default reads it as
    a sum with every coefficient 1.
    """
    import sympy

    vertices = list(pathAlg.quiver.nodes)
    relations = [relationReading(rel) for rel in pathAlg.rels]
    size = len(vertices)
    matrix = sympy.zeros(size, size)
    index = {vertex: position for position, vertex in enumerate(sorted(vertices))}
    for i in vertices:
        for j in vertices:
            matrix[index[j], index[i]] = homDimension(pathAlg.quiver, relations, i, j)
    return matrix


def coxeterPolyExact(pathAlg, relationReading=fromPathSet):
    """The Coxeter polynomial from the exact Cartan matrix."""
    cartan = cartanMatrixExact(pathAlg, relationReading)
    return (-cartan.inv().transpose() * cartan).charpoly()
